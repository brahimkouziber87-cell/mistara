export function getUnitsForFilter(
  cycle: EducationCycleId,
  _subject?: string,
  semester?: BankSemester | 'الكل',
  searchQuery?: string
): CompetencyFrameworkUnit[] {
  const q = normalizeArabicText(searchQuery || '');
  return COMPETENCY_FRAMEWORK_BANK.filter((unit) => {
    if (unit.cycle !== cycle) return false;
    if (semester && semester !== 'الكل' && unit.semester !== semester) return false;
    if (!q) return true;
    const haystack = normalizeArabicText(
      [
        unit.moduleTitle,
        unit.levelHint,
        unit.examContent,
        ...unit.competencies,
        ...unit.commonWeaknesses,
        ...unit.strengths,
        ...unit.remediationBullets,
      ].join(' ')
    );
    return haystack.includes(q);
  });
}

export function detectCycleFromMetadata(metadata: MassarMetadata): EducationCycleId {
  const combined = normalizeArabicText(`${metadata.cycle} ${metadata.level} ${metadata.className}`);
  if (
    /تاهيلي|ثانوي تاهيلي|بكالوريا|باكالوريا|جذع مشترك|\b(?:1|2)\s*b(?:ac)?[a-z0-9_-]*|\btc[a-z0-9_-]*/i.test(
      combined
    )
  ) {
    return 'high';
  }
  if (
    /اعدادي|1ac|2ac|3ac|apic|college|اولي اعدادي|ثانيه اعدادي|ثالثه اعدادي/i.test(combined)
  ) {
    return 'middle';
  }
  if (/ابتدائي|التعليم الاولي|سادس|خامس|رابع|primaire|ce\d|cm\d/i.test(combined)) {
    return 'primary';
  }
  return 'high';
}

export function matchCompetencyBankSelection(metadata: MassarMetadata): {
  cycle: EducationCycleId;
  subject: string;
  semester: BankSemester;
  unitId: string;
  matchedByMetadata: boolean;
} {
  const cycle = detectCycleFromMetadata(metadata);
  const matchedSubject = 'الرياضيات';

  const semNorm = normalizeArabicText(metadata.semester);
  const semester: BankSemester = /ثاني|2|s2/i.test(semNorm)
    ? 'الدورة الثانية'
    : 'الدورة الأولى';

  const candidates = getUnitsForFilter(cycle, matchedSubject, semester);
  const fallbackCandidates =
    candidates.length > 0 ? candidates : getUnitsForFilter(cycle, matchedSubject, 'الكل');

  const levelNorm = normalizeArabicText(
    `${metadata.level} ${metadata.className} ${metadata.examNumber}`
  );
  const scoreUnitMatch = (u: CompetencyFrameworkUnit): number => {
    const hintNorm = normalizeArabicText(`${u.levelHint} ${u.examHint} ${u.id}`);
    let score = 0;
    const is2Bac = /2\s*bac|ثانيه\s*بكالوريا|ثانيه\s*باك|\b2b(?:ac|[a-z]|$|\d|-|_)/i.test(levelNorm);
    const is1Bac = /1\s*bac|اولي\s*بكالوريا|اولي\s*باك|\b1b(?:ac|[a-z]|$|\d|-|_)/i.test(levelNorm);
    const isSM = /علوم\s*رياضيه|رياضيه|\bsm(?:[abf]|[-_\d\s]|$)|\b(?:1|2)b(?:ac)?sm(?:[abf]|[-_\d\s]|$)/i.test(levelNorm);
    const isEco = /اقتصاد|تدبير|محاسب|\bs?eco(?:f)?(?:[-_\d\s]|$)|\bsgc(?:f)?(?:[-_\d\s]|$)|\b(?:1|2)b(?:ac)?s?(?:eco|sgc)(?:f)?(?:[-_\d\s]|$)/i.test(levelNorm);
    const isLsh = /اداب|انسانيه|اصيل|شرعيه|lettre|\blsh(?:[-_\d\s]|$)|\btclsh(?:[-_\d\s]|$)|\btco(?:[-_\d\s]|$)|\bori(?:[-_\d\s]|$)|\b(?:1|2)b(?:ac)?(?:lsh|sh|l|ori)(?:[-_\d\s]|$)/i.test(levelNorm);
    const isTc = /جذع|\btc(?:s|sf|t|lsh|o|f)?(?:[-_\d\s]|$)/i.test(levelNorm);

    if (is2Bac && isSM && /2bac.*sm|ثانيه بكالوريا علوم رياضيه/.test(hintNorm)) score += 14;
    if (is1Bac && isSM && /1bac.*sm|اولي بكالوريا علوم رياضيه/.test(hintNorm)) score += 14;
    if (is1Bac && isEco && /high-math-1bac-eco|1bac eco/.test(hintNorm)) score += 14;
    if (is2Bac && isEco && /high-math-eco-s|2bac eco/.test(hintNorm)) score += 14;
    if (!is1Bac && !is2Bac && isEco && /اقتصاد|eco/.test(hintNorm)) score += 10;

    if (isTc && isLsh && /high-math-tclsh|tclsh/.test(hintNorm)) score += 14;
    if (is1Bac && isLsh && /high-math-lsh-s|1bac lsh/.test(hintNorm)) score += 14;
    if (is2Bac && isLsh && /high-math-2bac-lsh|2bac lsh/.test(hintNorm)) score += 14;
    if (!isTc && !is1Bac && !is2Bac && isLsh && /high-math-lsh-s/.test(hintNorm)) score += 10;

    if (isTc && !isLsh && /high-math-tc-s/.test(hintNorm)) score += 14;
    if (is1Bac && !isSM && !isEco && !isLsh && /high-math-1bac-se|1bac se/.test(hintNorm)) score += 13;
    if (is2Bac && !isSM && !isEco && !isLsh && /high-math-bac-s|2bac pc/.test(hintNorm)) score += 13;
    if (
      (is1Bac || is2Bac) &&
      !isSM &&
      !isEco &&
      !isLsh &&
      /بكالوريا|bac/.test(hintNorm) &&
      !/sm|eco|lsh/.test(hintNorm)
    ) {
      score += 4;
    }
    return score;
  };

  const bestUnit =
    [...fallbackCandidates].sort((a, b) => scoreUnitMatch(b) - scoreUnitMatch(a))[0] ||
    fallbackCandidates[0];

  return {
    cycle,
    subject: matchedSubject,
    semester,
    unitId: bestUnit?.id || '',
    matchedByMetadata: true,
  };
}
